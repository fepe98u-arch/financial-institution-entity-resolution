def generate_synthetic_journal(n_rows: int = 500, seed: int = 42) -> pl.DataFrame:
    """가상 분개 데이터를 Polars DataFrame으로 생성한다."""
    rng = random.Random(seed)
    weights = [t[4] for t in _TEMPLATES]
    picks = rng.choices(_TEMPLATES, weights=weights, k=n_rows)

    start_date = date(2025, 1, 1)
    voucher_dates = [start_date + timedelta(days=rng.randint(0, 364)) for _ in range(n_rows)]
    amounts = [rng.randint(10, 5000) * 1000 for _ in range(n_rows)]

    return pl.DataFrame(
        {
            "전표번호": [f"V{str(i + 1).zfill(6)}" for i in range(n_rows)],
            "전표일자": voucher_dates,
            "거래처": [p[0] for p in picks],
            "적요": [p[1] for p in picks],
            "계정과목": [p[2] for p in picks],
            "상대계정": [p[3] for p in picks],
            "금액": amounts,
        }
    )
